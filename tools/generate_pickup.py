#!/usr/bin/env python3
"""Pinned native B2W2 Pickup table and approved six-item extension; no Lua execution."""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'tools/references/pickup'
MANIFEST = ROOT / 'tools/references/pickup-sources.json'
NEW = {'SUN_STONE': 'sunStone', 'HEART_SCALE': 'heartScale', 'KINGS_ROCK': 'kingsRock',
       'IRON_BALL': 'ironBall', 'PRISM_SCALE': 'prismScale', 'LEFTOVERS': 'leftovers'}

def load():
    result = {}
    for name, pin in json.loads(MANIFEST.read_text())['files'].items():
        raw = (ROOT / pin['path']).read_bytes()
        if hashlib.sha256(raw).hexdigest() != pin['sha256']:
            raise ValueError('source checksum: ' + name)
        result[name] = raw.decode()
    return result

def collect(raw):
    constants = {}
    index = 0
    for line in raw['ids'].splitlines():
        match = re.match(r'ITEM_(\w+)(?: = (\d+))?$', line)
        if match:
            if match[2] is not None:
                index = int(match[2])
            constants[match[1]] = index
            index += 1
    def array(name):
        body = re.search(r'\b' + name + r'\[\d+\]\s*=\s*\{(.*?)\}', raw['return'], re.S)[1]
        return [constants[x] for x in re.findall(r'ITEM_(\w+)', body)]
    common, rare = array('sPickupItems'), array('sPickupRareItems')
    cutoffs = [int(x) for x in re.search(r'sPickupChances\[9\].*?\{(.*?)\}', raw['return'], re.S)[1].split(',')]
    assert len(common) == 18 and len(rare) == 11 and cutoffs == [30,40,50,60,70,80,90,94,98]
    table = [common[i:i+9] + [rare[i], rare[i+1]] for i in range(10)]
    items = {r['identifier']: r for r in csv.DictReader(io.StringIO(raw['prices']))}
    indices = {int(r['game_index']): int(r['item_id']) for r in csv.DictReader(io.StringIO(raw['indices'])) if r['generation_id'] == '5'}
    ids = {int(r['id']): r['identifier'] for r in csv.DictReader(io.StringIO(raw['items']))}
    mapping = {}
    for native in sorted(set(sum(table, []))):
        name = ids[indices[native]]
        parts = name.split('-')
        mapping[native] = parts[0] + ''.join(x.title() for x in parts[1:])
    additions = []
    for symbol, key in NEW.items():
        native = constants[symbol]
        api = indices[native]
        row = items[ids[api]]
        additions.append((symbol, key, native, api, int(row['cost'])))
    return table, mapping, additions

def render(raw):
    table, mapping, additions = collect(raw)
    lines = ['-- Generated by tools/generate_pickup.py from pinned B2W2 inputs.',
             '-- Approved field acquisition extension; existing Blue economy stays exact.',
             'PickupData = {', '    rows = {']
    for row in table:
        lines.append('        {' + ', '.join(map(str, row)) + '},')
    lines += ['    },', '    items = {']
    for native, key in mapping.items():
        lines.append(f'        [{native}] = "{key}",')
    lines += ['    },', '}', '']
    for symbol, key, native, api, cost in additions:
        name = symbol.replace('_', ' ')
        if key == 'kingsRock': name = "KING'S ROCK"
        lines += [f'assert(ItemData.definitions.{key} == nil and SpecimenData.holdable.{key} == nil, "duplicate Pickup item")',
                  f'ItemData.definitions.{key} = {{',
                  f'    id = "{key}", symbol = "{symbol}", name = "{name}",',
                  f'    gen5Id = {native}, pokeApiId = {api}, price = {cost}, sellPrice = {cost // 2},',
                  '    keyItem = false, category = "item", effect = "unsupported",',
                  '}', f'ItemData.bySymbol.{symbol} = "{key}"', f'SpecimenData.holdable.{key} = {api}', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    output = ROOT / 'Source/data/pickupData.lua'
    generated = render(load())
    if a.check:
        assert output.read_text() == generated, 'Pickup data drift'
    else:
        output.write_text(generated)
    print('110 native cells, 25 identities and six historical Gen V prices verified')
