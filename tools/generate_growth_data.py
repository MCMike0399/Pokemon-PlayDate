#!/usr/bin/env python3
"""Generate B2W2 growth tables with two independently maintained source checks.

Only --output is writable. Source caches are immutable/checksummed; --check
compares bytes and exits nonzero on drift. No live Source default output.
"""
import argparse
import csv
import hashlib
import io
import json
import math
from pathlib import Path
import re
import sys
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'tools/references/growth-sources.json'
# PokeAPI growth IDs -> cartridge / PKHeX growth byte.
GROWTH_IDS = {1: 5, 2: 0, 3: 4, 4: 3, 5: 1, 6: 2}
NAMES = ['medium-fast', 'erratic', 'fluctuating', 'medium-slow', 'fast', 'slow']

class GenerationError(ValueError):
    pass

def load_sources(cache, fetch=False, manifest=None):
    manifest = manifest or json.loads(MANIFEST.read_text())
    result = {}
    for name, spec in manifest['files'].items():
        path = Path(cache) / name
        if path.exists():
            raw = path.read_bytes()
        elif fetch:
            try:
                with urllib.request.urlopen(spec['url'], timeout=45) as response:
                    raw = response.read()
            except OSError as error:
                raise GenerationError(f'fetch failed for {name}: {error}') from error
        else:
            raise GenerationError(f'missing pinned input {path}; use --fetch')
        if hashlib.sha256(raw).hexdigest() != spec['sha256']:
            raise GenerationError(f'checksum mismatch: {name}; cache preserved')
        result[name] = raw
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    return result

def rows(raw, required):
    try:
        reader = csv.DictReader(io.StringIO(raw.decode('utf-8')))
        if not set(required) <= set(reader.fieldnames or []):
            raise GenerationError(f'CSV schema missing {required}')
        result = list(reader)
        if not result or any(None in row or None in row.values() for row in result):
            raise GenerationError('empty/malformed CSV')
        return result
    except (UnicodeError, csv.Error) as error:
        raise GenerationError(f'invalid CSV: {error}') from error

def collect(raw):
    tables = {i: {} for i in range(6)}
    for row in rows(raw['experience.csv'], ['growth_rate_id', 'level', 'experience']):
        group, level, xp = GROWTH_IDS[int(row['growth_rate_id'])], int(row['level']), int(row['experience'])
        if level in tables[group]: raise GenerationError('duplicate growth threshold')
        tables[group][level] = xp
    text = raw['Experience.cs'].decode('utf-8')
    for group in range(6):
        found = re.search(r'Growth' + str(group) + r'\s*=>\s*\[(.*?)\];', text, re.S)
        if not found: raise GenerationError(f'missing independent growth table {group}')
        independent = [int(n) for n in re.findall(r'\d+', found.group(1))]
        if set(tables[group]) != set(range(1, 101)) or len(independent) != 100:
            raise GenerationError('incomplete growth table')
        if [tables[group][n] for n in range(1, 101)] != independent:
            raise GenerationError(f'independent growth table disagreement: {group}')
        if independent[0] != 0 or any(a >= b for a, b in zip(independent, independent[1:])):
            raise GenerationError('invalid growth progression')
    rates = rows(raw['growth_rates.csv'], ['id','identifier'])
    for row in rates:
        if {1:'slow',2:'medium',3:'fast',4:'medium-slow',5:'slow-then-very-fast',6:'fast-then-very-slow'}[int(row['id'])] != row['identifier']:
            raise GenerationError('growth identifier mapping disagreement')
    species = {}
    binary = raw['personal_b2w2']
    if len(binary) != 53884: raise GenerationError('unexpected B2W2 personal record length')
    for row in rows(raw['pokemon_species.csv'], ['id','growth_rate_id']):
        dex = int(row['id'])
        if not 1 <= dex <= 151: continue
        group = GROWTH_IDS[int(row['growth_rate_id'])]
        offset = dex * 76
        if binary[offset + 0x15] != group:
            raise GenerationError(f'independent species growth disagreement: {dex}')
        if dex in species: raise GenerationError('duplicate species ID')
        species[dex] = (group, int.from_bytes(binary[offset + 0x22:offset + 0x24], 'little'))
    if set(species) != set(range(1, 152)): raise GenerationError('incomplete original151 species')
    return tables, species

def scaled_power(n):
    """Q12 nearest square root, half up; then floor sqrt(n)*n*n."""
    square = n * 4096**2
    root = math.isqrt(square)
    if 4 * square >= (2 * root + 1)**2: root += 1
    return root * n * n // 4096

def render(raw):
    tables, species = collect(raw)
    lines = ['-- Generated by tools/generate_growth_data.py; immutable pins in growth-sources.json.',
             '-- Growth IDs use the B2W2 personal-table byte, not PokeAPI IDs.', 'GrowthData = {', '    thresholds = {']
    for group in range(6):
        lines.append(f'        [{group}] = {{ -- {NAMES[group]}')
        for start in range(1, 101, 10):
            lines.append('            ' + ', '.join(str(tables[group][n]) for n in range(start, start+10)) + ',')
        lines.append('        },')
    lines += ['    },', '    species = { -- [National Dex] = {growth byte, Gen V base EXP}']
    lines += [f'        [{dex}] = {{{group}, {xp}}},' for dex, (group, xp) in sorted(species.items())]
    lines += ['    },', '    scaledPower = { -- floor(round(sqrt(n)*4096)*n*n/4096), n=1..210']
    for start in range(1, 211, 10):
        lines.append('        ' + ', '.join(str(scaled_power(n)) for n in range(start, min(start+10,211))) + ',')
    lines += ['    },', '}', '']
    return '\n'.join(lines)

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, required=True)
    parser.add_argument('--fetch', action='store_true')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    try:
        generated = render(load_sources(args.cache, args.fetch))
        if args.check:
            if not args.output.exists() or args.output.read_text() != generated:
                raise GenerationError(f'generated growth data drift: {args.output}')
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(generated)
        print('growth data: 151 species, 600 independently checked thresholds, 210 Q12 coefficients')
        return 0
    except (GenerationError, OSError, ValueError, KeyError) as error:
        print(f'growth generation failed: {error}', file=sys.stderr)
        return 1

if __name__ == '__main__':
    raise SystemExit(main())
