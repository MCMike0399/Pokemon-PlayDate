#!/usr/bin/env python3
"""Project explicit Gen V bypasssub flags from checksum-verified local sources."""
import argparse
import hashlib
import json
import re
from pathlib import Path

from tools.check_contact_ability_sources import load, DEFAULT_CACHE, MANIFEST, ROOT
from tools.generate_ability_move_metadata import entries
from tools.move_producer_contract import read_rows

ARTIFACT = ROOT / 'tools/references/substitute-policy.json'
LUA = ROOT / 'Source/battle/substitutePolicy.lua'


def project(sources, keys):
    resolved = {}
    for name in ['ps_data_moves.ts'] + [f'ps_data_mods_gen{g}_moves.ts' for g in (8, 7, 6, 5)]:
        for key, body in entries(sources[name]).items():
            flags = re.search(r'^\t\tflags:\s*\{([^}]*)\}', body, re.M | re.S)
            if flags:
                resolved[key] = bool(re.search(r'\bbypasssub:\s*1\b', flags[1]))
    result = {}
    for key in keys:
        identifier = {'viceGrip': 'visegrip'}.get(key, key.lower())
        if identifier not in resolved:
            raise ValueError('missing primary flag policy: ' + key)
        result[key] = resolved[identifier]
    return result


def build(cache=DEFAULT_CACHE):
    sources = load(cache)
    pins = json.loads(MANIFEST.read_text())
    names = ['ps_data_moves.ts'] + [f'ps_data_mods_gen{g}_moves.ts' for g in (8, 7, 6, 5)]
    keys = list(read_rows((ROOT / 'Source/battle/moves.lua').read_text()))
    runtime = ROOT / 'Source/data/fieldMoveBattleData.lua'
    runtime_keys = re.findall(r'^moveData\.(\w+)\s*=\s*Move\s*\{', runtime.read_text(), re.M)
    if not runtime_keys or set(keys) & set(runtime_keys) or len(runtime_keys) != len(set(runtime_keys)):
        raise ValueError('invalid runtime move policy inventory')
    keys.extend(runtime_keys)
    rows = project(sources, keys)
    artifact = dict(schema=1, generation=5, revision=pins['revision'],
                    source_sha256={name: pins['files'][name]['sha256'] for name in names},
                    runtime_move_source=dict(path='Source/data/fieldMoveBattleData.lua',
                        sha256=hashlib.sha256(runtime.read_bytes()).hexdigest()),
                    bypass=rows)
    raw = (json.dumps(artifact, indent=2) + '\n').encode()
    text = '-- Generated by tools/generate_substitute_policy.py; Gen V explicit bypasssub only.\n'
    text += '-- Policy SHA256: ' + hashlib.sha256(raw).hexdigest() + '\n'
    text += '-- Sound and Infiltrator do not add bypass in Gen V. Missing keys fail closed.\n'
    text += 'SubstitutePolicy = {\n'
    text += ''.join('    ' + key + ' = ' + str(value).lower() + ',\n' for key, value in rows.items())
    text += '}\n'
    return raw, text


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, default=DEFAULT_CACHE)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw, text = build(args.cache)
    if args.check:
        assert ARTIFACT.read_bytes() == raw, 'Substitute oracle policy drift'
        assert LUA.read_text() == text, 'Substitute Lua policy drift'
    else:
        ARTIFACT.write_bytes(raw)
        LUA.write_text(text)
