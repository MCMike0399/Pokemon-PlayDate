#!/usr/bin/env python3
"""Generate pinned original151 B2W2 ability slots,25 natures,Blue holdability."""
import argparse,csv,hashlib,io,json,re,sys,urllib.request
from pathlib import Path
from generate_items import load as load_items,collect as collect_items
MANIFEST=Path(__file__).parent/'references/specimen-sources.json'
class GenerationError(ValueError):pass

def load(cache,fetch=False,manifest=None):
    manifest=manifest or json.loads(MANIFEST.read_text());out={}
    for name,row in manifest['files'].items():
        path=Path(cache)/name
        if path.exists():raw=path.read_bytes()
        elif fetch:
            raw=urllib.request.urlopen(row['url'],timeout=30).read()
            if hashlib.sha256(raw).hexdigest()!=row['sha256']:raise GenerationError('checksum mismatch: '+name)
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(raw)
        else:raise GenerationError('missing source: '+name)
        if hashlib.sha256(raw).hexdigest()!=row['sha256']:raise GenerationError('checksum mismatch: '+name+'; cache preserved')
        out[name]=raw
    return out

def rows(raw):return list(csv.DictReader(io.StringIO(raw.decode())))
def hold_set(text):
    out=set()
    for name in ('General','Medicine','Berry'):
        match=re.search(r'\b'+name+r'\s*=>\s*\[(.*?)\];',text,re.S)
        if not match:raise GenerationError('unsupported Gen5 held storage schema: '+name)
        body=re.sub(r'//[^\n]*','',match.group(1));out.update(int(x) for x in re.findall(r'\d+',body))
    if not {1,4,17,81,149,236}<=out or 328 in out or 442 in out:raise GenerationError('unexpected Gen5 held whitelist')
    return out

def collect(raw,item_rows):
    personal=raw['personal_b2w2']
    if len(personal)%76 or len(personal)<152*76:raise GenerationError('invalid B2W2 personal rows')
    if b'SIZE = 0x4C' not in raw['PersonalInfo5B2W2.cs'] or b'Data[0x18]' not in raw['PersonalInfo5B2W2.cs']:raise GenerationError('unsupported personal schema')
    ids={int(r['id']):r['identifier'] for r in rows(raw['abilities.csv'])}
    names={int(r['ability_id']):r['name'] for r in rows(raw['ability_names.csv']) if r['local_language_id']=='9'}
    species=[];needed=set()
    for dex in range(1,152):
        fields=list(personal[dex*76+24:dex*76+27])
        if len(fields)!=3 or any(x not in ids or x not in names or x>164 or x<1 for x in fields):raise GenerationError('unknown GenV ability slot: '+str(dex))
        species.append(fields);needed.update(fields)
    nature_text=raw['bw_src_system_poke_tool.c'].decode();marker='static const s8 natureStat[NATURE_COUNT][NATURE_STAT_COUNT] = {'
    if marker not in nature_text:raise GenerationError('unsupported nature schema')
    table=nature_text.split(marker,1)[1].split('\n};',1)[0];natures=[]
    for values,name in re.findall(r'\{([^}]+)\},?\s*// NATURE_(\w+)',table):
        signs=[int(x.strip()) for x in values.split(',')]
        if len(signs)!=5 or any(x not in (-1,0,1) for x in signs) or sum(signs)!=0 or signs.count(1)>1:raise GenerationError('invalid nature row')
        natures.append((name.title(),signs))
    if len(natures)!=25 or natures[0][0]!='Hardy' or natures[24][0]!='Quirky':raise GenerationError('incomplete nature table')
    item_ids={r['identifier']:int(r['id']) for r in rows(raw['items.csv'])};held=hold_set(raw['ItemStorage5.cs'].decode());holdable={}
    aliases={'PARLYZ_HEAL':'paralyze-heal','X_SPECIAL':'x-sp-atk','X_DEFEND':'x-defense','ELIXER':'elixir','MAX_ELIXER':'max-elixir'}
    for key,item in sorted(item_rows.items()):
        if item['keyItem'] or item['category'] in ('tm','hm') or item['symbol']=='EXP_ALL':holdable[key]=False;continue
        identity=aliases.get(item['symbol'],item['symbol'].lower().replace('_','-'))
        if identity not in item_ids:raise GenerationError('missing GenV item mapping: '+item['symbol'])
        item_id=item_ids[identity]
        if item_id not in held:raise GenerationError('unreviewed nonholdable ordinary item: '+key)
        holdable[key]=item_id
    return species,natures,{x:names[x] for x in sorted(needed)},holdable

def quote(s):return json.dumps(s,ensure_ascii=True)
def render(raw,item_rows):
    species,natures,names,held=collect(raw,item_rows)
    out=['-- Generated by tools/generate_specimen_data.py; pinned B2W2 original151.','SpecimenData = {','    version = 1,','    slots = {']
    for dex,values in enumerate(species,1):out.append(f'        [{dex}] = {{first={values[0]},second={values[1]},hidden={values[2]}}},')
    out+=['    },','    natures = {']
    for nature,(name,values) in enumerate(natures):out.append(f'        [{nature}] = {{name={quote(name)},atk={values[0]},def={values[1]},spa={values[2]},spd={values[3]},spe={values[4]}}},')
    out+=['    },','    abilityNames = {']
    for aid,name in names.items():out.append(f'        [{aid}] = {quote(name)},')
    out+=['    },','    holdable = {']
    for key,value in held.items():out.append(f'        {key} = '+('false' if value is False else str(value))+',')
    out+=['    },','}'];return '\n'.join(out)+'\n'

def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--cache',type=Path,required=True);p.add_argument('--items-cache',type=Path,required=True);p.add_argument('--fetch',action='store_true');p.add_argument('--output',type=Path,required=True);p.add_argument('--check',action='store_true');a=p.parse_args(argv)
    try:
        generated=render(load(a.cache,a.fetch),collect_items(load_items(a.items_cache,a.fetch))[0])
        if a.check:
            if not a.output.is_file() or a.output.read_text()!=generated:raise GenerationError('generated specimen data drift: '+str(a.output))
        else:
            project=Path(__file__).resolve().parents[1]
            if a.output.resolve().is_relative_to(project/'Source'):raise GenerationError('write an explicit temporary candidate outside project Source')
            a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text(generated)
    except Exception as e:print(str(e),file=sys.stderr);return 1
    return 0
if __name__=='__main__':raise SystemExit(main())
