#!/usr/bin/env python3
"""Generate fail-closed dispatch metadata from the reviewed support inventory.

This inventory describes implemented singles handlers, not mechanics acceptance.
New move IDs require explicit review; power and a nonempty effects array alone
cannot establish that a special move is implemented.
"""
import argparse
import json
from pathlib import Path
from tools.move_producer_contract import read_rows

ROOT = Path(__file__).resolve().parents[1]
HANDLERS = {'engine-dsl', 'dsl', 'standard-damage', 'intentional-no-effect', 'singles-no-target', 'wild-escape', 'battle-condition', 'switch-intercept'}


def render(root=ROOT):
    inventory = json.loads((root / 'tools/references/move-support.json').read_text())
    rows = read_rows((root / 'Source/battle/moves.lua').read_text())
    entries = inventory['moves']
    if inventory['schema'] != 1 or set(entries) != set(rows):
        raise ValueError('move support inventory must cover the exact move registry')
    lines = ['-- Generated by tools/generate_move_support.py; review the inventory before changing.',
             '-- Dispatch support only; this does not certify every Gen V interaction.',
             'MoveSupport = { handlers = {}, gaps = {} }']
    for key, entry in entries.items():
        if set(entry) == {'handler'} and entry['handler'] in HANDLERS:
            field, value = 'handlers', entry['handler']
        elif set(entry) == {'gap'} and isinstance(entry['gap'], str) and entry['gap']:
            field, value = 'gaps', entry['gap']
        else:
            raise ValueError('invalid move support entry: ' + key)
        lines.append(f'MoveSupport.{field}.{key} = {json.dumps(value)}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'Source/battle/moveSupport.lua'
    text = render()
    if args.check:
        if path.read_text() != text:
            raise ValueError('generated move support metadata drift')
    else:
        path.write_text(text)


if __name__ == '__main__':
    main()
