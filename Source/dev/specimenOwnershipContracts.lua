SpecimenOwnershipContracts={}
local function eq(a,b,label)assert(a==b,(label or "value")..": expected "..tostring(b)..", got "..tostring(a))end
local function same(a,b)
    eq(type(a),type(b));if type(a)~="table" then eq(a,b);return end
    for k,v in pairs(a)do same(v,b[k])end;for k in pairs(b)do assert(a[k]~=nil,"extra field "..tostring(k))end
end
local function rng()return RulesRNG.snapshot()end
local function withOwner(session,fn)
    local old,prior=GameSession.activeRNGSession(),rng();assert(session:activateRNG())
    local ok,why=pcall(fn)
    local current=GameSession.activeRNGSession();if current then assert(current:deactivateRNG())end
    if old then assert(old:activateRNG())end;RulesRNG.restore(prior)
    assert(ok,why)
end
local function gameWithMon()
    local game=GameContext();assert(game:recruit(Pokemon("charmander",5)))
    assert(game.session:setIntro({stage="done",starter="charmander",rivalStarter="squirtle"}))
    return game
end
local function debug(game)
    game.machine:register("base",State("base"));local state=DebugState(game);game.machine:register("debug",state)
    game.machine:change("base");game.machine:push("debug");return state
end
function SpecimenOwnershipContracts.run()
    local report={ok=true,passed=0,failed=0,tests={}}
    local function test(name,fn)local ok,why=pcall(fn);report.tests[#report.tests+1]={name=name,ok=ok,error=not ok and tostring(why)or nil};if ok then report.passed=report.passed+1 else report.failed=report.failed+1;report.ok=false end end
    test("Inactive and foreign sessions cannot consume active global creation stream",function()
        local actor,foreign=GameContext(),GameContext()
        withOwner(actor.session,function()
            local before=rng();local mon,why=Specimen.createForSession(foreign.session,"eevee",5,"trainer")
            eq(mon,nil);eq(why,"inactive-specimen-session");same(rng(),before)
            eq(Specimen.createForSession(nil,"eevee",5,"wild"),nil);same(rng(),before)
            local detached=RulesRNG.new(42);assert(Specimen.create("eevee",5,"wild",detached));eq(detached:snapshot().rolls,9);same(rng(),before)
        end)
    end)
    test("Actual active session creation commits exactly its intended rules continuation",function()
        local game=GameContext()
        withOwner(game.session,function()
            RulesRNG.seed(42);local mon,receipt=Specimen.createForSession(game.session,"eevee",5,"starter");assert(mon,receipt)
            eq(mon.natureId,22);eq(mon.abilitySlot,"second");eq(rng().rolls,9);eq(GameSession.activeRNGSession(),game.session)
            same(game.session:rngData(),RulesRNG.toData())
        end)
    end)
    test("Inactive starter selection leaves intro party world and RNG unchanged",function()
        local game=GameContext();local before=rng();local intro=game.session:getIntro();local world=WorldDeltas.export()
        local ok,why=pcall(Story.chooseStarter,game,"charmander");eq(ok,false);assert(tostring(why):find("inactive%-specimen%-session"),tostring(why))
        eq(game.session:party():count(),0);same(game.session:getIntro(),intro);same(WorldDeltas.export(),world);same(rng(),before)
    end)
    test("Full party starter refusal and multi-member debug reset validate before draws",function()
        local game=gameWithMon();local first=game.session:party():get(1);local second=Pokemon("squirtle",5);assert(game:recruit(second))
        withOwner(game.session,function()
            local before=rng();local ok,why=pcall(game.resetFixturePokemon,game,"pikachu",10)
            eq(ok,false);assert(tostring(why):find("reset the whole fixture",1,true),tostring(why));same(rng(),before)
            eq(game.session:party():count(),2);eq(game.session:party():get(1),first);eq(game.session:party():get(2),second)
            ok,why=pcall(Story.chooseStarter,game,"bulbasaur");eq(ok,false);assert(tostring(why):find("empty party",1,true),tostring(why));same(rng(),before)
        end)
    end)
    test("Inactive debug wild action leaves stack and stream untouched",function()
        local game=gameWithMon();debug(game);local before=rng();game.debugMenu:doWildBattle("rattata",3)
        eq(game.machine:getCurrent(),"debug");eq(game.debugMenu.isActive,true);same(rng(),before)
        game.machine:change("base")
    end)
    test("Failed debug creation does not pop its scene or commit partial RNG",function()
        local game=gameWithMon()
        withOwner(game.session,function()
            debug(game);local before=RulesRNG.new(42):snapshot();before.rolls=2147483646;RulesRNG.restore(before)
            game.debugMenu:doWildBattle("rattata",3);eq(game.machine:getCurrent(),"debug");eq(game.debugMenu.isActive,true);same(rng(),before)
            game.machine:change("base")
        end)
    end)
    test("Reentered debug callback and replaced session cannot start a battle",function()
        local game=gameWithMon()
        withOwner(game.session,function()
            debug(game);local old=game.debugMenu.onClose;game.machine:pop();game.machine:push("debug")
            local before=rng();eq(old(),false);same(rng(),before);eq(game.machine:getCurrent(),"debug")
            local current=game.debugMenu.onClose;game.session=GameContext().session;eq(current(),false);same(rng(),before)
            eq(game.machine:getCurrent(),"debug");game.machine:change("base")
        end)
    end)
    test("Production encounter owner is checked before species level or attribute draws",function()
        local actor,foreign=GameContext(),GameContext();assert(actor:recruit(Pokemon("charmander",5)));assert(actor.session:setIntro({stage="done",starter="charmander",rivalStarter="squirtle"}));local zone=Zone({name="owner contract",tileRows={"Fo"},encounters={{species="rattata",minLevel=3,maxLevel=3,weight=1}}})
        withOwner(actor.session,function()
            local before=rng();local ok,why=pcall(zone.rollEncounter,zone,foreign.session)
            eq(ok,false);assert(tostring(why):find("inactive%-encounter%-session"),tostring(why));same(rng(),before)
            RulesRNG.seed(42);eq(zone:rollEncounter(actor.session).species,"rattata");eq(rng().rolls,11)
        end)
    end)
    return report
end
