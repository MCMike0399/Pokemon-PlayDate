local function equal(actual,wanted,label)
    assert(actual==wanted,(label or "value") .. ": expected " .. tostring(wanted) .. ", got " .. tostring(actual))
end
local function sameRNG(a,b)
    for _,key in ipairs({"algorithm","seed","state","rolls"}) do equal(a[key],b[key],key) end
end
local function own(mon,keys,pp)
    mon.moves,mon.pp={},{}
    for i,key in ipairs(keys) do mon.moves[i]=key;mon.pp[key]=pp or moveData[key].maxPP end
end
local function settle(b)
    local messages,count={},0
    while b:phase()=="script" do
        count=count+1;assert(count<500,"battle script failed to settle")
        messages[#messages+1]=b.message
        b.machine:get("script"):advance()
    end
    return table.concat(messages,"|")
end
local function roster(...)
    local p=Party();for _,mon in ipairs({...}) do assert(p:add(mon)) end;return p
end
local function sessionWithStarter()
    local session=GameSession.newSession({itemDefinitions=ItemData.definitions,validateWorld=WorldDeltas.validate,
        resolveLocation=WorldDeltas.resolveLocation},{location={zone_id="reds_house_2f",x=5,y=3,facing="up"},seed=42})
    local p=Pokemon("charmander",5);assert(session:recruit(p))
    assert(session:setIntro({stage="done",starter="charmander",rivalStarter="squirtle",rivalOutcome=false}))
    return session,p
end
local function fresh(p,e,party,session,enemyParty,trainer)
    local b=Battle(p,e,trainer,{party=party,session=session,enemyParty=enemyParty})
    settle(b);return b
end
