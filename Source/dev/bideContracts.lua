local function eq(a,b,label)assert(a==b,(label or "value")..": expected "..tostring(b)..", got "..tostring(a))end
local function sameRNG(before)local now=RulesRNG.snapshot();eq(now.state,before.state,"RNG state");eq(now.rolls,before.rolls,"RNG rolls")end
local function own(p,keys)p.moves,p.pp={},{};for _,k in ipairs(keys)do p.moves[#p.moves+1]=k;p.pp[k]=moveData[k].pp end end
local function settle(b)
    local lines={};local n=0
    while b:phase()=="script"do n=n+1;assert(n<300,"script stuck: "..tostring(b.message));assert(not b.pendingLearning,"unexpected learning")
        lines[#lines+1]=b.message;b.machine:get("script"):advance()
    end
    return table.concat(lines,"|")
end
local function fresh(p,e)
    local b=Battle(p or Pokemon("rattata",100),e or Pokemon("rattata",100));settle(b);own(b.player,{"bide"});own(b.enemy,{"harden"});return b
end
local function attempt(b,side)
    b:runScript(function()return b:resolveTurn({side=side or "player",actor=b[side or "player"],key="bide",move=moveData.bide,continuation=b.conditions:lockedKey(b[side or "player"])=="bide"})end)
    return settle(b)
end
local function auto(b)eq(b:phase(),"command");b:update();eq(b:phase(),"script");return settle(b)end
local function findSeed(fn)for i=1,10000 do if fn(RulesRNG.new(i))then return i end end;error("no bounded seed")end
